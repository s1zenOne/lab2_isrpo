def area(a, h):
    '''
    Принимает длину основания треугольника a и высоту h, возвращает площадь треугольника.

    Формула:
        S = (a * h) / 2

    Параметры:
        a (float): длина основания треугольника
        h (float): высота, проведённая к основанию

    Возвращаемое значение:
        float: площадь треугольника

    Пример:
        >>> area(6, 4)
        12.0
    '''
    return a * h / 2


def perimeter(a, b, c):
    '''
    Принимает длины сторон треугольника a, b, c и возвращает его периметр.

    Формула:
        P = a + b + c

    Параметры:
        a (float): длина первой стороны
        b (float): длина второй стороны
        c (float): длина третьей стороны

    Возвращаемое значение:
        float: периметр треугольника

    Пример:
        >>> perimeter(3, 4, 5)
        12
    '''
    return a + b + c
